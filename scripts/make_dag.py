#!/usr/bin/env python3
"""Turn `snakemake --rulegraph` into the rule-graph diagrams used in the docs.

The diagrams are generated from the workflow itself, so they cannot drift from the code:

    python scripts/make_dag.py                       # writes docs/img/dag_*.mmd and dag_*.txt
    python scripts/make_dag.py --check               # exit 1 if the committed files are out of date
    snakemake -s workflows/TTpipe.snakefile --configfile ... --rulegraph | python scripts/make_dag.py --stdin full

Outputs, per mode (full / processing / analysis), in docs/img/:
    dag_<mode>.mmd   Mermaid flowchart (renders on GitHub and in Quarto)
    dag_<mode>.txt   plain-text stage listing (for PDF exports, which do not render Mermaid)
    dag_<mode>.svg   only if Graphviz `dot` is installed
It also refreshes the full-workflow diagram embedded between `<!-- dag:start -->` and `<!-- dag:end -->`
in README.md and CODE_GUIDE.md (and checks them with --check).

`all` (the target rule) is dropped: every leaf feeds it, so it only adds clutter.
Needs only the standard library plus snakemake (for --rulegraph); no data files are read.
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IMG = ROOT / "docs" / "img"
SNAKEFILE = "workflows/TTpipe.snakefile"
BASE_CONFIG = "config/TTpipeConfig.yaml"
FIXTURES = "tests/dryrun"

## Which rules belong to which stage (anything else is listed under "Other").
STAGES = [
    ("Processing", ["fastqc", "fastp", "star_index", "star_align", "mapq_filter", "mark_duplicates",
                    "split_strands", "merge_bams", "scale_factors", "bigwig", "bigwig_sample",
                    "gene_info", "htseq_count", "count_matrix"]),
    ("Analysis", ["sample_table", "deseq2", "rnk", "fgsea", "sankey", "results_explorer",
                 "stranded_signal"]),
    ("Reporting", ["qc_summary", "qc_report", "multiqc"]),
]

## Each mode = (config file in tests/dryrun, extra --config overrides). The full-mode graph turns on every
## optional branch so the diagram shows all rules: fastp (trim), star_index (build_star_index), per-sample
## tracks and fgsea (a GSEA collection).
MODES = {
    "full": ("config.yaml", ["trim=True", "build_star_index=True", "sample_tracks=True",
                             "gsea_collections={Hallmarks: tests/dryrun/placeholder.gmt}"]),
    "processing": ("config_processing_only.yaml", ["multiqc=True"]),
    "analysis": ("config_analysis_only.yaml", ["gsea_collections={Hallmarks: tests/dryrun/placeholder.gmt}"]),
}
TITLES = {"full": "Full workflow (all optional branches on)",
          "processing": "Processing only (run_analysis: false)",
          "analysis": "Analysis only (run_processing: false)"}


def rulegraph(mode):
    cfgfile, extra = MODES[mode]
    cmd = ["snakemake", "-s", SNAKEFILE, "--cores", "1", "--configfile", BASE_CONFIG, f"{FIXTURES}/{cfgfile}",
           "--rulegraph"]
    if extra:
        cmd += ["--config", *extra]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"snakemake --rulegraph failed for mode {mode!r}:\n{r.stderr[-2000:]}")
    return r.stdout


def parse_dot(dot):
    """Return (nodes, edges): rule names and (upstream, downstream) pairs, `all` removed."""
    names = dict(re.findall(r'^\s*(\d+)\[label = "([^"]+)"', dot, flags=re.M))
    edges = [(names[a], names[b]) for a, b in re.findall(r"^\s*(\d+) -> (\d+)", dot, flags=re.M)]
    nodes = [n for n in names.values() if n != "all"]
    edges = sorted({(a, b) for a, b in edges if "all" not in (a, b)})
    return nodes, edges


def stage_of(rule):
    for name, rules in STAGES:
        if rule in rules:
            return name
    return "Other"


def mermaid(nodes, edges, title):
    ids = {n: n.replace("-", "_") for n in nodes}
    out = ["flowchart LR"]
    for stage in [s for s, _ in STAGES] + ["Other"]:
        members = [n for n in nodes if stage_of(n) == stage]
        if not members:
            continue
        out.append(f'  subgraph {stage}["{stage}"]')
        out += [f"    {ids[n]}[{n}]" for n in members]
        out.append("  end")
    out += [f"  {ids[a]} --> {ids[b]}" for a, b in edges]
    return f"%% {title}: generated by scripts/make_dag.py from `snakemake --rulegraph`; do not edit\n" + "\n".join(out) + "\n"


def text(nodes, edges, title):
    """Stage-by-stage listing with each rule's upstream rules, for places that cannot render Mermaid."""
    up = {n: sorted(a for a, b in edges if b == n) for n in nodes}
    lines = [f"{title} (generated by scripts/make_dag.py; do not edit)", ""]
    for stage in [s for s, _ in STAGES] + ["Other"]:
        members = [n for n in nodes if stage_of(n) == stage]
        if not members:
            continue
        lines.append(stage.upper())
        for n in members:
            lines.append(f"  {n:<16} <- {', '.join(up[n]) if up[n] else '(inputs from the samplesheet / config)'}")
        lines.append("")
    return "\n".join(lines)


STAGE_COLORS = {"Processing": "#e8f0fe", "Analysis": "#e6f4ea", "Reporting": "#fef7e0", "Other": "#f1f3f4"}


def clean_dot(nodes, edges, title):
    """Graphviz source for the same cleaned graph as the Mermaid output: no `all`, rules grouped by stage."""
    out = ['digraph TTpipe {', f'  label="{title}"; labelloc=t; fontname="Helvetica"; fontsize=14;',
           '  rankdir=TB; compound=true; nodesep=0.3; ranksep=0.5;',
           '  node [shape=box, style="rounded,filled", fillcolor=white, fontname="Helvetica", fontsize=11];',
           '  edge [color="#80868b", arrowsize=0.7];']
    for i, stage in enumerate([s for s, _ in STAGES] + ["Other"]):
        members = [n for n in nodes if stage_of(n) == stage]
        if members:
            out.append(f'  subgraph cluster_{i} {{ label="{stage}"; style="rounded,filled"; '
                       f'fillcolor="{STAGE_COLORS[stage]}"; color="#dadce0"; fontname="Helvetica";')
            out += [f'    "{n}";' for n in members]
            out.append("  }")
    out += [f'  "{a}" -> "{b}";' for a, b in edges]
    out.append("}")
    return "\n".join(out) + "\n"


def svg(dot, path):
    if shutil.which("dot") is None:
        return False
    r = subprocess.run(["dot", "-Tsvg"], input=dot, capture_output=True, text=True)
    if r.returncode == 0:
        path.write_text(r.stdout)
        return True
    return False


def build(mode, dot=None):
    dot = dot or rulegraph(mode)
    nodes, edges = parse_dot(dot)
    return dot, mermaid(nodes, edges, TITLES[mode]), text(nodes, edges, TITLES[mode])


def sync_embeds(mmd, check):
    """Keep the Mermaid block between the dag markers of README.md / CODE_GUIDE.md equal to the full diagram."""
    body = "".join(mmd.splitlines(keepends=True)[1:])          # drop the generated-by comment line
    block = f"<!-- dag:start -->\n```mermaid\n{body}```\n<!-- dag:end -->"
    stale = []
    for name in ("README.md", "CODE_GUIDE.md"):
        path = ROOT / name
        if not path.exists():
            continue
        old = path.read_text()
        new, n = re.subn(r"<!-- dag:start -->.*?<!-- dag:end -->", lambda m: block, old, count=1, flags=re.S)
        if n and new != old:
            if check:
                stale.append(name)
            else:
                path.write_text(new)
                print(f"updated DAG block in {name}")
    return stale


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("modes", nargs="*", metavar="MODE", help="one or more of: " + ", ".join(MODES) + " (default: all)")
    ap.add_argument("--stdin", action="store_true", help="read a dot rulegraph from stdin (needs exactly one mode)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if committed files differ")
    args = ap.parse_args()
    bad = [m for m in args.modes if m not in MODES]   # not argparse `choices=`: on Python 3.11 an empty default fails it
    if bad:
        ap.error(f"unknown mode(s) {bad}; choose from {list(MODES)}")
    modes = args.modes or list(MODES)
    if args.stdin and len(modes) != 1:
        ap.error("--stdin needs exactly one mode")
    IMG.mkdir(parents=True, exist_ok=True)
    stale = []
    for mode in modes:
        dot, mmd, txt = build(mode, sys.stdin.read() if args.stdin else None)
        if mode == "full":
            stale += sync_embeds(mmd, args.check)
        for path, content in ((IMG / f"dag_{mode}.mmd", mmd), (IMG / f"dag_{mode}.txt", txt)):
            if args.check:
                if not path.exists() or path.read_text() != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(content)
                print(f"wrote {path.relative_to(ROOT)}")
        nodes, edges = parse_dot(dot)
        if not args.check and svg(clean_dot(nodes, edges, TITLES[mode]), IMG / f"dag_{mode}.svg"):
            print(f"wrote docs/img/dag_{mode}.svg")
    if stale:
        sys.exit("out of date (run scripts/make_dag.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
