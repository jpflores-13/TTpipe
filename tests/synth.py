"""SYNTHETIC TTpipe output directories for the QC-report tests.

Everything generated here is INVENTED by a random number generator: it is not real TT-seq data and says
nothing about real library quality. The file layouts follow workflows/rules/common.smk (STAR Log.final.out,
ReadsPerGene, mapq / final-pair one-liners, a Picard MarkDuplicates metrics file, HTSeq-style count
matrices, gene_info, DESeq2 summary / VST tables). The STAR and Picard layouts were written from memory of
those tools' output, not copied from real runs.
"""
import os

import numpy as np

SYNTH_NOTICE = "SYNTHETIC TEST DATA: generated by tests/synth.py, not real TT-seq results."

CONDITIONS = ["DMSO", "2H"]
REPS = ["rep1", "rep2"]
N_GENES = 400


def sample_names(conditions=CONDITIONS, reps=REPS):
    return [(f"S_{c}_{r}", c, r) for c in conditions for r in reps]


def star_log_text(n_in, uniq, multi, toomany, mism, short, other):
    """STAR Log.final.out-like text (percentages given as numbers)."""
    n_uniq = int(n_in * uniq / 100)
    return f"""                                 Started job on |\tNov 17 00:00:00
                          Number of input reads |\t{n_in}
                      Average input read length |\t200
                                    UNIQUE READS:
                   Uniquely mapped reads number |\t{n_uniq}
                        Uniquely mapped reads % |\t{uniq:.2f}%
                          Average mapped length |\t198.00
                       Number of splices: Total |\t1000
                             MULTI-MAPPING READS:
        Number of reads mapped to multiple loci |\t{int(n_in * multi / 100)}
             % of reads mapped to multiple loci |\t{multi:.2f}%
        Number of reads mapped to too many loci |\t{int(n_in * toomany / 100)}
             % of reads mapped to too many loci |\t{toomany:.2f}%
                                  UNMAPPED READS:
  Number of reads unmapped: too many mismatches |\t0
       % of reads unmapped: too many mismatches |\t{mism:.2f}%
            Number of reads unmapped: too short |\t{int(n_in * short / 100)}
                 % of reads unmapped: too short |\t{short:.2f}%
                Number of reads unmapped: other |\t{int(n_in * other / 100)}
                     % of reads unmapped: other |\t{other:.2f}%
                                  CHIMERIC READS:
                       Number of chimeric reads |\t0
                            % of chimeric reads |\t0.00%
"""


def picard_text(pairs_examined, dup_frac, library="Unknown Library", decimal_comma=False):
    """Picard MarkDuplicates metrics file layout (comments, METRICS CLASS, header, row, HISTOGRAM)."""
    dups = int(pairs_examined * dup_frac)
    pct = f"{dup_frac:.6f}"
    if decimal_comma:
        pct = pct.replace(".", ",")
    return (f"## htsjdk.samtools.metrics.StringHeader\n# MarkDuplicates INPUT=x.bam OUTPUT=y.bam\n"
            f"## htsjdk.samtools.metrics.StringHeader\n# Started on: synthetic\n\n"
            f"## METRICS CLASS\tpicard.sam.DuplicationMetrics\n"
            "LIBRARY\tUNPAIRED_READS_EXAMINED\tREAD_PAIRS_EXAMINED\tSECONDARY_OR_SUPPLEMENTARY_RDS\tUNMAPPED_READS\t"
            "UNPAIRED_READ_DUPLICATES\tREAD_PAIR_DUPLICATES\tREAD_PAIR_OPTICAL_DUPLICATES\tPERCENT_DUPLICATION\t"
            "ESTIMATED_LIBRARY_SIZE\n"
            f"{library}\t0\t{pairs_examined}\t0\t0\t0\t{dups}\t0\t{pct}\t\n\n"
            "## HISTOGRAM\tjava.lang.Double\nBIN\tVALUE\n1.0\t1.0\n")


# name -> per-sample quality knobs
GOOD = dict(n_in=40_000_000, uniq=88.0, multi=5.0, toomany=0.5, mism=0.0, short=4.0, other=0.5,
            dup=0.25, sense=0.97)
POOR = dict(n_in=3_000_000, uniq=45.0, multi=35.0, toomany=2.0, mism=0.0, short=15.0, other=3.0,
            dup=0.62, sense=0.55)


def _counts(rng, n_genes, conds, reps, de_genes=60):
    """Gene x sample matrix (negative binomial) with a condition effect for the first `de_genes` genes."""
    base = rng.lognormal(mean=6.0, sigma=1.5, size=n_genes)
    out = {}
    for ci, (c, r) in enumerate(zip(conds, reps)):
        mu = base.copy()
        if c != CONDITIONS[0]:
            mu[:de_genes] *= 3.0
        out[(c, r)] = rng.negative_binomial(50, 50 / (50 + mu))
    return out


def make_run(outdir, mode="full", poor=(), seed=1, decimal_comma=False, conditions=CONDITIONS, reps=REPS):
    """Create a synthetic output dir. mode: 'full', 'processing' (no analysis files) or 'analysis'
    (only a count matrix, returned as a path; nothing else is written under counts/ or <sample>/).

    Returns dict(outdir, samplesheet, config, counts, samples) with paths.
    """
    rng = np.random.default_rng(seed)
    rows = sample_names(conditions, reps)
    names = [r[0] for r in rows]
    os.makedirs(outdir, exist_ok=True)
    sheet = os.path.join(outdir, "samplesheet.txt")
    with open(sheet, "w") as fh:
        fh.write("Name\tCondition\tReplicate\n")
        for n, c, r in rows:
            fh.write(f"{n}\t{c}\t{r}\n")
    cfg = os.path.join(outdir, "config.yaml")
    with open(cfg, "w") as fh:
        fh.write("genome: 'synthetic'\nstrandedness: 'dUTP'\ncount_strand: 'sum'\nreference_condition: "
                 f"'{conditions[0]}'\nalpha: 0.01\nmin_mapq: 10\nremove_duplicates: true\n"
                 "qc_thresholds:\n"
                 "  input_pairs_million:    {direction: higher_is_better, warn: 20,  fail: 5}\n"
                 "  unique_pct:             {direction: higher_is_better, warn: 70,  fail: 50}\n"
                 "  multi_pct:              {direction: lower_is_better,  warn: 15,  fail: 30}\n"
                 "  too_short_pct:          {direction: lower_is_better,  warn: 20,  fail: 40}\n"
                 "  duplicate_pct:          {direction: lower_is_better,  warn: 40,  fail: 50}\n"
                 "  sense_pct:              {direction: higher_is_better, warn: 90,  fail: 75}\n"
                 "  rrna_pct:               {direction: lower_is_better,  warn: 5,   fail: 15}\n"
                 "  replicate_correlation:  {direction: higher_is_better, warn: 0.95, fail: 0.85}\n")

    # genes: first 60 are the 'DE' genes; alternate strands; ~3% rRNA
    gene_ids = [f"SYN{i:05d}" for i in range(N_GENES)]
    gtype = ["rRNA" if i % 33 == 0 else ("Mt_rRNA" if i == 7 else "protein_coding") for i in range(N_GENES)]
    strand = ["+" if i % 2 == 0 else "-" for i in range(N_GENES)]
    counts = _counts(rng, N_GENES, [r[1] for r in rows], [r[2] for r in rows])
    mat = {n: counts[(c, r)] for n, c, r in rows}
    result = dict(outdir=outdir, samplesheet=sheet, config=cfg, samples=names, counts=None)

    def write_matrix(path, m):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh:
            fh.write("gene_id\t" + "\t".join(names) + "\n")
            for gi, g in enumerate(gene_ids):
                fh.write(g + "\t" + "\t".join(str(int(m[n][gi])) for n in names) + "\n")

    if mode == "analysis":
        path = os.path.join(outdir, "external_counts.txt")
        write_matrix(path, mat)
        result["counts"] = path
        _write_gene_info(outdir, gene_ids, gtype, strand)
        return result

    # --- per-sample stats (processing) ---
    fwd, rev = {}, {}
    for n, _c, _r in rows:
        k = POOR if n in poor else GOOD
        st = os.path.join(outdir, n, "stats")
        os.makedirs(st, exist_ok=True)
        with open(os.path.join(st, f"{n}_Log.final.out"), "w") as fh:
            fh.write(star_log_text(k["n_in"], k["uniq"], k["multi"], k["toomany"], k["mism"], k["short"], k["other"]))
        uniq_pairs = int(k["n_in"] * k["uniq"] / 100)
        mapq = int(uniq_pairs * 0.97)
        final = int(mapq * (1 - k["dup"]))
        with open(os.path.join(st, f"{n}_mapq.txt"), "w") as fh:
            fh.write(f"{n}\t{mapq}\n")
        with open(os.path.join(st, f"{n}_final_pairs.txt"), "w") as fh:
            fh.write(f"{n}\t{final}\n")
        with open(os.path.join(st, f"{n}_dedupMetrics.txt"), "w") as fh:
            fh.write(picard_text(mapq, k["dup"], decimal_comma=decimal_comma))
        # STAR ReadsPerGene: dUTP => read1 opposite strand (col 4) is sense
        sense = k["sense"]
        with open(os.path.join(st, f"{n}_ReadsPerGene.out.tab"), "w") as fh:
            fh.write("N_unmapped\t100\t100\t100\nN_multimapping\t50\t50\t50\nN_noFeature\t900\t900\t900\nN_ambiguous\t10\t10\t10\n")
            for gi, g in enumerate(gene_ids):
                c = int(mat[n][gi])
                s = int(round(c * sense))
                fh.write(f"{g}\t{c}\t{c - s}\t{s}\n")  # same strand = antisense part, opposite = sense part
        # strand-split HTSeq-like counts: forward = transcribed from + strand
        f, r = np.zeros(N_GENES, int), np.zeros(N_GENES, int)
        for gi in range(N_GENES):
            c = int(mat[n][gi])
            s = int(round(c * sense))
            if strand[gi] == "+":
                f[gi], r[gi] = s, c - s
            else:
                f[gi], r[gi] = c - s, s
        fwd[n], rev[n] = f, r
    write_matrix(os.path.join(outdir, "counts", "counts_forward.txt"), fwd)
    write_matrix(os.path.join(outdir, "counts", "counts_reverse.txt"), rev)
    total = {n: fwd[n] + rev[n] for n in names}
    write_matrix(os.path.join(outdir, "counts", "counts_deseq2.txt"), total)
    result["counts"] = os.path.join(outdir, "counts", "counts_deseq2.txt")
    _write_gene_info(outdir, gene_ids, gtype, strand)

    # tracks (empty placeholder .bw files: only names/sizes are listed by the report)
    tr = os.path.join(outdir, "tracks")
    os.makedirs(tr, exist_ok=True)
    with open(os.path.join(tr, "scale_factors.tsv"), "w") as fh:
        fh.write("condition\tmapped_pairs\tscale_factor\tsource\n")
        for c in conditions:
            fh.write(f"{c}\t{30_000_000}\t1.0\tcomputed\n")
    for c in conditions:
        for suffix in ("", "_forward", "_reverse"):
            with open(os.path.join(tr, f"{c}{suffix}.bw"), "wb") as fh:
                fh.write(b"SYNTHETIC-PLACEHOLDER")

    if mode == "full":
        d = os.path.join(outdir, "analysis", "deseq2")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "deg_summary.tsv"), "w") as fh:
            fh.write("comparison\tn_up\tn_down\tn_tested\n")
            for c in conditions[1:]:
                fh.write(f"{c}_vs_{conditions[0]}\t55\t3\t{N_GENES}\n")
        lc = np.log2(np.array([total[n] for n in names]).T + 1.0)
        with open(os.path.join(d, "vst.tsv"), "w") as fh:
            fh.write("\t".join([""] + names) + "\n")  # R write.table(col.names=NA) style: blank first header
            for gi, g in enumerate(gene_ids):
                fh.write(g + "\t" + "\t".join(f"{v:.4f}" for v in lc[gi]) + "\n")
    return result


def _write_gene_info(outdir, gene_ids, gtype, strand):
    p = os.path.join(outdir, "counts")
    os.makedirs(p, exist_ok=True)
    with open(os.path.join(p, "gene_info.tsv"), "w") as fh:
        fh.write("gene_id\tgene_name\tgene_type\tchr\tstart\tend\tstrand\tlength\n")
        for i, g in enumerate(gene_ids):
            fh.write(f"{g}\tGene{i}\t{gtype[i]}\tchrSyn\t{i * 1000 + 1}\t{i * 1000 + 900}\t{strand[i]}\t900\n")
